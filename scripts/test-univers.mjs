import assert from "node:assert/strict";
import { parcoursUnivers, illustrationUnivers } from "../public/univers.js";
import { themeMission, decorMission, phraseProgres } from "../public/decors-mission.js";
const missions=[{id:3,titre:"Géo",statut:"a_faire"},{id:1,titre:"Maths",statut:"terminee"},{id:2,titre:"Sciences",statut:"en_cours"}];
const espace=parcoursUnivers(missions,"espace"),medieval=parcoursUnivers(missions,"medieval");
assert.deepEqual(espace.map(q=>q.id),[1,2,3]);
assert.deepEqual(espace.map(q=>q.explore),[true,false,false]);
assert.equal(espace[0].lieu,"La station de départ");assert.equal(medieval[0].lieu,"Le village des artisans");
assert.deepEqual(espace.map(q=>[q.id,q.statut]),medieval.map(q=>[q.id,q.statut]),"Un changement d’univers garde les mêmes missions et leur état");
assert.deepEqual(missions.map(q=>q.id),[3,1,2],"Le parcours ne modifie pas la liste source");
assert.equal(themeMission({matiere:"Sciences",aventure:"espace"}),"fusee");
assert.equal(themeMission({titre:"Fusée",aventure:"medieval"}),"royaume");
assert.ok(decorMission("royaume",5,5).includes("6 parties construites"));
assert.ok(!decorMission("royaume",5,5).includes("détruites"));
assert.equal(phraseProgres("royaume"),"Tu as pris le temps de travailler cette mission.");
assert.ok(illustrationUnivers("espace").includes("Une fusée"));assert.ok(illustrationUnivers("medieval").includes("Un village"));
const potager = parcoursUnivers(missions,"jardin");
assert.equal(potager[0].lieu,"Le coin des graines");
assert.deepEqual(potager.map(q=>[q.id,q.statut]),espace.map(q=>[q.id,q.statut]));
assert.equal(themeMission({titre:"Fusée",matiere:"Maths",aventure:"jardin"}),"fleurs");
assert.ok(illustrationUnivers("jardin").includes("Le potager et les fleurs"));
console.log("OK univers : lieux distincts, progression réelle, missions conservées et château construit sans combat.");
